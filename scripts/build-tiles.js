'use strict';
/*
 * Bakes the FluffyStuff public-domain Riichi tile face SVGs (downloaded into
 * .tiles-src/) into a single tiles-data.js the client loads with zero network
 * dependency. We keep only the inner artwork (defs + drawables), rebased onto a
 * shared viewBox, and strip Inkscape editor cruft. Flowers/seasons are not in
 * that set, so those are left to the hand-drawn fallback in tiles-svg.js.
 *
 *   node scripts/build-tiles.js
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '.tiles-src');
const OUT = path.join(__dirname, '..', 'public', 'tiles-data.js');

// tile kind (0..33) -> source file name in the FluffyStuff set
const MAP = {};
for (let i = 0; i < 9; i++) MAP[i] = `Man${i + 1}`;         // characters
for (let i = 0; i < 9; i++) MAP[9 + i] = `Pin${i + 1}`;     // dots (circles)
for (let i = 0; i < 9; i++) MAP[18 + i] = `Sou${i + 1}`;    // bamboo
MAP[27] = 'Ton'; MAP[28] = 'Nan'; MAP[29] = 'Shaa'; MAP[30] = 'Pei'; // E S W N
MAP[31] = 'Chun'; MAP[32] = 'Hatsu'; MAP[33] = 'Haku';       // red, green, white dragons

function clean(svg) {
  // drop XML/doctype/comments
  svg = svg.replace(/<\?xml[\s\S]*?\?>/g, '').replace(/<!--[\s\S]*?-->/g, '');
  // grab inner of <svg>, and its viewBox
  const vb = (svg.match(/viewBox="([^"]*)"/) || [])[1] || '0 0 300 400';
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  let body = inner;
  // remove editor-only blocks
  body = body.replace(/<metadata[\s\S]*?<\/metadata>/g, '');
  body = body.replace(/<sodipodi:namedview[\s\S]*?<\/sodipodi:namedview>/g, '');
  body = body.replace(/<sodipodi:namedview[^>]*\/>/g, '');
  body = body.replace(/<inkscape:path-effect[\s\S]*?\/>/g, '');
  // strip inkscape/sodipodi attributes
  body = body.replace(/\s(inkscape|sodipodi):[\w-]+="[^"]*"/g, '');
  // collapse whitespace
  body = body.replace(/\s+/g, ' ').replace(/>\s+</g, '><').trim();
  return { vb, body };
}

const out = {};
for (const [kind, name] of Object.entries(MAP)) {
  const file = path.join(SRC, `${name}.svg`);
  if (!fs.existsSync(file)) { console.warn('MISSING', file); continue; }
  const { vb, body } = clean(fs.readFileSync(file, 'utf8'));
  out[kind] = { vb, body };
}

const header = '/* Auto-generated by scripts/build-tiles.js — DO NOT EDIT.\n' +
  '   Tile face artwork derived from FluffyStuff/riichi-mahjong-tiles (public domain). */\n';
fs.writeFileSync(OUT, header + 'window.MJ_TILE_DATA = ' + JSON.stringify(out) + ';\n');

const bytes = fs.statSync(OUT).size;
console.log(`wrote ${Object.keys(out).length} tiles -> ${OUT} (${(bytes / 1024).toFixed(1)} KB)`);
